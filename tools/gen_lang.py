def esc(s: str) -> str:
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == '\\':
            out.append('\\\\')
        elif o < 128:
            out.append(ch)
        else:
            out.append('\\u%04x' % o)
    return ''.join(out)

def main():
    # zh_CN comes straight from the key list
    T["zh_CN"] = {name: zh for name, zh in KEYS}

    root = os.path.join(os.path.dirname(__file__), '..', 'src', 'app', 'lang')
    os.makedirs(root, exist_ok=True)

    # StrTable.h - the shared enum
    with open(os.path.join(root, 'StrTable.h'), 'w', encoding='utf-8', newline='\n') as f:
        f.write("#pragma once\n")
        f.write("// GENERATED by tools/gen_lang.py - do not edit by hand.\n")
        f.write("// String ids shared by every language table; order matters.\n\n")
        f.write("namespace micp { namespace lang {\nenum class Str {\n")
        for i, (name, _) in enumerate(KEYS):
            f.write("    %s = %d,\n" % (name, i))
        f.write("};\nconstexpr int kStrCount = %d;\n}} // namespace micp::lang\n" % len(KEYS))

    total = 0
    for code in LANG_ORDER:
        table = T[code]
        missing = [name for name, _ in KEYS if name not in table]
        if missing:
            raise SystemExit("%s is missing translations for: %s" % (code, ', '.join(missing)))
        total += len(KEYS)
        with open(os.path.join(root, code + '.h'), 'w', encoding='utf-8', newline='\n') as f:
            f.write("// GENERATED by tools/gen_lang.py - do not edit by hand.\n")
            f.write("// %s UI strings. ASCII-only: non-ASCII codepoints are \\uXXXX escapes.\n" % code)
            f.write("// Only included by app/Lang.cpp.\n\n")
            f.write("namespace micp { namespace lang { namespace strings {\n\n")
            f.write("static const wchar_t* const %s[] = {\n" % code)
            for name, zh in KEYS:
                f.write('    /* %-18s */ L"%s",\n' % (name, esc(table[name])))
            f.write("};\n\n}}} // namespace micp::lang::strings\n")
    print("generated %d tables x %d strings (%d total) -> src/app/lang/" % (len(LANG_ORDER), len(KEYS), total))

if __name__ == '__main__':
    main()
